/**
 * The system exercise library (§4.3).
 *
 * Each row carries the taxonomy that makes charts work: a primary muscle,
 * weighted secondaries for partial volume credit, a movement pattern, and a
 * tracking type that decides which input UI the set row renders.
 *
 * `bodyweightFactor` is the fraction of bodyweight the movement actually
 * lifts — without it, a set of pull-ups registers as zero load.
 */

import type { Equipment, MovementPattern, TrackingType } from '@/domain/types'

export interface ExerciseSeed {
  name: string
  primary: string
  /** [muscleId, contribution] — partial credit toward that muscle's volume. */
  secondary?: [string, number][]
  equipment: Equipment
  pattern: MovementPattern
  /** Defaults to `weight_reps`, which covers most of the library. */
  tracking?: TrackingType
  bodyweightFactor?: number
  unilateral?: boolean
  aliases?: string[]
}

