-- Any row not covered (user-authored rows) gets a safe placeholder equal to the
-- name; the client repair (repairExerciseRows) rewrites these to a proper
-- movement on next launch. Guarantees `movement <> ''` post-migration.
update exercises set movement = name where movement = '';

-- Enforce the invariant: no exercise without a movement.
alter table exercises add constraint exercises_movement_not_empty
  check (length(movement) > 0);

-- Group scans in the library go through this index.
create index exercises_movement on exercises (movement);
