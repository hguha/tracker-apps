-- Add a movement grouping slug to exercises, so the library and picker can
-- present one "Bench Press" with a barbell/dumbbell/smith chooser rather than
-- three separate rows. Additive and non-destructive: workout_exercises, sets,
-- and personal_records still key on the exercise id, so records and history
-- stay per (movement + equipment) with no re-keying.
--
-- The derivation strips one equipment word (barbell/dumbbell/cable/…) from the
-- name — grip and angle (Incline, Close-Grip) stay in the movement and mark a
-- distinct lift. Kept as a stored column, not a computed view, because two
-- library rows with the same computed name are legitimate ("Cable Crunch" is a
-- weighted movement, not the bodyweight "Crunch"), and users authoring a
-- custom exercise need to opt out of the default grouping.
--
-- The static CASE below is generated from EXERCISE_SEEDS via movementFor() in
-- src/domain/movement.ts (via supabase/generate-seed.mjs's audit) so server and
-- client can never disagree on the seeded rows. Anything not in the case (user
-- rows written pre-migration) gets a client-side repair on next launch — see
-- repairExerciseRows() in src/db/seed/index.ts.

alter table exercises add column movement text not null default '';

